package eventos;

public class Aluno {
    String nome;
    String turma;
    int nota;
    String email;
    int idade;

    public Aluno(String nome, String turma, int nota, String email, int idade) {
        this.nome = nome;
        this.turma = turma;
        this.nota = nota;
        this.email = email;
        this.idade = idade;
    }
}
